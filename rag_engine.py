def extract_zone_codes(text: str) -> list[str]:
    """Extract zone codes from user message in any format.
    Catches: სზ-4, სზ 4, სზ4, საცხოვრებელი ზონა 4, ზონა 4 etc.
    Always normalizes to dash format (სზ-4)."""
    import re
    codes = set()

    # Direct code formats: სზ-4, სზ 4, სზ4
    for m in re.findall(r'([\u10D0-\u10FF]{1,4})[\s\-]?(\d+)', text):
        codes.add(f"{m[0]}-{m[1]}")

    # Written out: საცხოვრებელი ზონა 4, საცხოვრებელ ზონა 4-ზე etc.
    zone_map = {
        'საცხოვრებელ': 'სზ',
        'საზოგადოებრივ': 'სსზ',
        'სატრანსპორტო': 'ტზ',
        'შერეულ': 'შზ',
        'ინდუსტრიულ': 'იზ',
        'სპეციალურ': 'სპზ',
    }
    for word, prefix in zone_map.items():
        for m in re.findall(word + r'[\u10D0-\u10FF]*\s+ზონა[\u10D0-\u10FF\s]*(\d+)', text):
            codes.add(f"{prefix}-{m}")

    return list(codes)


def chat_with_history(messages: list[dict]) -> str:
    """
    Send full conversation history to Claude with retrieved document context.
    messages: list of {"role": "user"/"assistant", "content": "..."}
    """
    last_user_message = next(
        (m["content"] for m in reversed(messages) if m["role"] == "user"), ""
    )

    try:
        retriever = get_retriever()
        nodes = retriever.retrieve(last_user_message)
    except Exception:
        nodes = []

    # Keyword lookup: zone codes + important topic keywords
    zone_codes = extract_zone_codes(last_user_message)

    # Topic keywords that need direct lookup (semantic search misses them)
    topic_keywords = []
    keyword_triggers = {
        'სახანძრო': ['სახანძრო'],
        'ხანძარ': ['სახანძრო'],
        'ღიობ': ['ღიობ'],
        'პანდუს': ['პანდუს'],
        'ევაკუაც': ['ევაკუაც'],
        'კვამლ': ['კვამლ'],
        'ზონის ცვლილ': ['სპეციალური'],
        'ზონის შეცვლ': ['სპეციალური'],
        'ზონიდან': ['სპეციალური'],
        'ზონალური შეთანხმ': ['სპეციალური'],
        'სპეციალური ზონალ': ['სპეციალური'],
        'ფუნქციური ზონის': ['სპეციალური'],
    }
    for trigger, keywords in keyword_triggers.items():
        if trigger in last_user_message:
            topic_keywords.extend(keywords)

    if zone_codes or topic_keywords:
        try:
            chroma_client = chromadb.PersistentClient(path="./chroma_db")
            col = chroma_client.get_collection("georgian_regulations")
        except Exception:
            zone_codes = []
            topic_keywords = []
            col = None
    if zone_codes or topic_keywords:
        existing_ids = {n.node_id for n in nodes}
        all_results = col.get(include=["documents", "metadatas"])

        search_terms = zone_codes + topic_keywords

        # Detect if query is about residential buildings
        residential_query = any(w in last_user_message for w in [
            'საცხოვრებელ', 'მრავალბინიანი', 'სახლ', 'ბინ', 'აპარტამენტ'
        ])

        for term in search_terms:
            added = 0
            limit = 10 if term == 'სახანძრო' else 5

            # For fire safety + residential: prioritize chunks containing both
            scored = []
            for doc, meta, doc_id in zip(
                all_results["documents"], all_results["metadatas"], all_results["ids"]
            ):
                if term in doc and doc_id not in existing_ids:
                    score = 2 if (residential_query and any(
                        w in doc for w in ['საცხოვრებელ', 'სც-', 'მრავალბინიანი']
                    )) else 1
                    scored.append((score, doc, meta, doc_id))

            scored.sort(key=lambda x: x[0], reverse=True)
            for score, doc, meta, doc_id in scored:
                if added >= limit:
                    break
                from llama_index.core.schema import TextNode, NodeWithScore
                node = TextNode(text=doc, metadata=meta, id_=doc_id)
                nodes.append(NodeWithScore(node=node, score=float(score)))
                existing_ids.add(doc_id)
                added += 1
    context = "\n\n---\n\n".join([n.get_content() for n in nodes])

    # Only keep last 6 messages (3 turns) to limit token cost
    trimmed_messages = messages[-6:] if len(messages) > 6 else messages

    # Use ALL user messages for section detection so follow-up answers don't lose context
    all_user_text = " ".join(m["content"] for m in messages if m["role"] == "user")
    dynamic_prompt = build_dynamic_prompt(all_user_text)

    system_blocks = [
        {
            "type": "text",
            "text": dynamic_prompt,
            "cache_control": {"type": "ephemeral"},
        },
    ]
    if context:
        system_blocks.append({
            "type": "text",
            "text": f"\n\nშემდეგი დოკუმენტების ამონარიდები გამოიყენე პასუხისთვის:\n\n{context}",
        })

    client = anthropic.Anthropic(api_key=get_api_key())
    response = client.messages.create(
        model="claude-sonnet-4-6",
        max_tokens=2000,
        system=system_blocks,
        messages=trimmed_messages,
    )
    return response.content[0].text


def has_documents():
    """Check if any documents have been indexed."""
    try:
        chroma_client = chromadb.PersistentClient(path="./chroma_db")
        collection = chroma_client.get_or_create_collection("georgian_regulations")
        return collection.count() > 0
    except Exception:
        return False
