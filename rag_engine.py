def build_dynamic_prompt(user_message: str) -> str:
    """Return core rules + only the section(s) relevant to user_message."""
    import re

    # Split on trigger lines: - "term1", "term2" ... — კითხვისას გამოიყენე
    trigger_pattern = re.compile(
        r'\n(?=- ".*?(?:კითხვისას გამოიყენე|კითხვისას გამოიყენე))',
    )
    parts = trigger_pattern.split(SYSTEM_PROMPT)

    core = parts[0]
    selected = [core]

    msg_lower = user_message.lower()

    for part in parts[1:]:
        # Extract quoted terms from trigger line (first line of part)
        first_line = part.split('\n')[0]
        terms = re.findall(r'"([^"]+)"', first_line)
        if any(t.lower() in msg_lower for t in terms):
            selected.append(part)

    # Always include website rules (last ~7 lines of SYSTEM_PROMPT)
    # They are in core already since they don't have a trigger pattern
    return '\n'.join(selected)


